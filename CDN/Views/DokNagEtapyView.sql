create view cdn.DokNagEtapyView
(  	   [DnE_DnEId]
      ,[DnE_DnPrID]
      ,[DnE_Typ]
      ,[DnE_Symbol]
      ,[DnE_Nazwa]
      ,[DnE_OpeId]
      ,[DnE_Wykonany]
      ,[DnE_Obowiazkowy]
      ,[DnE_CzyTerminWykonania]
      ,[DnE_TerminWykonania]
      ,[DnE_TerminOd]
      ,[DnE_TerminDo]
      ,[DnE_RezerwujCzas]
      ,[DnE_Przypomnienie]
      ,[DnE_CzasPrzypomnienia]
      ,[DnE_Komentarz]
)
as
select
	   [DnE_DnEId]
      ,[DnE_DnPrID]
      ,[DnE_Typ]
      ,(select top 1 SE_Symbol from [SRV1].[CDN_KNF_ONE].CDN.SekEtapy where SE_SEID=DnE_EtapID) As [DnE_Symbol]
      ,(select top 1 SE_Nazwa  from [SRV1].[CDN_KNF_ONE].CDN.SekEtapy where SE_SEID=DnE_EtapID) As [DnE_Nazwa]
      ,[DnE_OpeId]
      ,[DnE_Wykonany]
      ,[DnE_Obowiazkowy]
      ,[DnE_CzyTerminWykonania]
      ,[DnE_TerminWykonania]
      ,[DnE_TerminOd]
      ,[DnE_TerminDo]
      ,[DnE_RezerwujCzas]
      ,[DnE_Przypomnienie]
      ,[DnE_CzasPrzypomnienia]
      ,[DnE_Komentarz]
from cdn.DokNagEtapy
union all
select
	   [DnE_DnEId]
      ,[DnE_DnPrID]
      ,[DnE_Typ]
      ,[SE_Symbol] As [DnE_Symbol]
      ,[SE_Nazwa]  As [DnE_Nazwa]
      ,[DnE_OpeId]
      ,[DnE_Wykonany]
      ,[DnE_Obowiazkowy]
      ,[DnE_CzyTerminWykonania]
      ,[DnE_TerminWykonania]
      ,[DnE_TerminOd]
      ,[DnE_TerminDo]
      ,[DnE_RezerwujCzas]
      ,[DnE_Przypomnienie]
      ,[DnE_CzasPrzypomnienia]
      ,[DnE_Komentarz]
from [SRV1].[CDN_KNF_ONE].cdn.DokNagEtapy
join [SRV1].[CDN_KNF_ONE].cdn.SekEtapy on SE_SEID=DnE_EtapID