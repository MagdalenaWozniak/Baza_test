CREATE   VIEW cdn.WyposazenieAtrybutyView
( WyAV_WyAVID,
 WyAV_SrAId,
 WyAV_DeAId,
 WyAV_WypID,
 WyAV_AtrybutFormat,
 WyAV_AtrybutKod,
 WyAV_AtrybutNazwa,
 WyAV_AtrybutWartosc,
 WyAV_Lp,
 WyAV_DokumentTyp,
 WyAV_DokumentID,
 WyAV_DokumentNr,
 WyAV_DataZak,
 WyAV_NumerKPR,
 WyAV_Nazwa,
 WyAV_KatID,
 WyAV_Kategoria,
 WyAV_NrInwent,
 WyAV_WartoscZakup,
 WyAV_Ilosc,
 WyAV_JednostkaMiary,
 WyAV_PrcID,
 WyAV_PrcNazwisko,
 WyAV_DataLikw,
 WyAV_Stan,
 WyAV_Likwidacja,
 WyAV_LikwDokument,
 WyAV_Opis,
 WyAV_OpeZalID,
 WyAV_StaZalId,
 WyAV_TS_Zal,
 WyAV_OpeModID,
 WyAV_StaModId,
 WyAV_TS_Mod)
AS
select
 REPLICATE('0', 10-LEN(Convert(NVARCHAR(10), IsNULL(Wyp_Lp,0))))+Convert(NVARCHAR(10), IsNULL(Wyp_Lp,0))+
 IsNull(DeA_Kod, 'Z')+REPLICATE('Z', 20-LEN(IsNull(DeA_Kod,'Z')))+
 REPLICATE('0', 10-LEN(Convert(NVARCHAR(10), IsNULL(Wyp_WypID,0))))+Convert(NVARCHAR(10), IsNULL(Wyp_WypID,0))+
 REPLICATE('0', 10-LEN(Convert(NVARCHAR(10), IsNULL(DeA_DeAId,0))))+Convert(NVARCHAR(10), IsNULL(DeA_DeAId,0)),
 SrA_SrAId,
 DeA_DeAId,
 Wyp_WypID,
 DeA_Format,
 DeA_Kod,
 DeA_Nazwa,
 SrA_WartoscTxt,
 Wyp_Lp,
 Wyp_DokumentTyp,
 Wyp_DokumentID,
 Wyp_DokumentNr,
 Wyp_DataZak,
 Wyp_NumerKPR,
 Wyp_Nazwa,
 Wyp_KatID,
 Wyp_Kategoria,
 Wyp_NrInwent,
 Wyp_WartoscZakup,
 Wyp_Ilosc,
 Wyp_JednostkaMiary,
 Wyp_PrcID,
 Wyp_PrcNazwisko,
 Wyp_DataLikw,
 Wyp_Stan,
 Wyp_Likwidacja,
 Wyp_LikwDokument,
 Wyp_Opis,
 Wyp_OpeZalID,
 Wyp_StaZalId,
 Wyp_TS_Zal,
 Wyp_OpeModID,
 Wyp_StaModId,
 Wyp_TS_Mod
from
CDN.Wyposazenie
left outer join CDN.TrwaleAtrybuty ON (Wyp_WypID=SrA_WypID)
left outer join CDN.DefAtrybuty ON (SrA_DeAId=DeA_DeAId)
