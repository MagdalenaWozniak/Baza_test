create view cdn.DokNagView
(DNV_DoNID, DNV_DDfId, DNV_SSID,DNV_ProcesKod,DNV_EtapBiezacyLp, DNV_NumerObcy, DNV_NumerString, DNV_NumerPelny, DNV_NumerNr, DNV_DataDok, DNV_Tytul, DNV_Dotyczy, DNV_OpiekunID,
DNV_OpiekunTyp, DNV_Status, DNV_Typ, DNV_Katalog, DNV_KatalogSymbol, DNV_KatalogNazwa, DNV_OriginId,
DNV_OpeZalID, DNV_StaZalId, DNV_TS_Zal, DNV_OpeModID, DNV_StaModId, DNV_TS_Mod)
as
select
	DoN_DoNID,
	DoN_DDfId,
	DoN_SSID,
	DoN_ProcesKod,
	DoN_EtapBiezacyLp,
	DoN_NumerObcy,
	DoN_NumerString,
	CDN.FN_NUMERPELNY(DON_NUMERNR,DON_NUMERSTRING),
	DoN_NumerNr,
	DoN_DataDok,
	DoN_Tytul,
	DoN_Dotyczy,
	DoN_OpiekunID,
	DoN_OpiekunTyp,
	DoN_Status,
	DoN_Typ,
	DoN_Katalog,
	Ktl_Symbol,
	Ktl_Nazwa,
	DoN_OriginId,
	DoN_OpeZalID,
	DoN_StaZalId,
	DoN_TS_Zal,
	DoN_OpeModID,
	DoN_StaModId,
	DoN_TS_Mod
FROM cdn.DokNag LEFT JOIN cdn.Katalogi ON DoN_Katalog = Ktl_KtlId
union all
select
	DoN_DoNID,
	DoN_DDfId,
	DoN_SSID,
	DoN_ProcesKod,
	DoN_EtapBiezacyLp,
	DoN_NumerObcy,
	DoN_NumerString,
	CDN.FN_NUMERPELNY(DON_NUMERNR,DON_NUMERSTRING),
	DoN_NumerNr,
	DoN_DataDok,
	DoN_Tytul,
	DoN_Dotyczy,
	DoN_OpiekunID,
	DoN_OpiekunTyp,
	DoN_Status,
	DoN_Typ,
	DoN_Katalog,
	Ktl_Symbol,
	Ktl_Nazwa,
	DoN_OriginId,
	DoN_OpeZalID,
	DoN_StaZalId,
	DoN_TS_Zal,
	DoN_OpeModID,
	DoN_StaModId,
	DoN_TS_Mod
FROM [SRV1].[CDN_KNF_ONE].cdn.DokNag LEFT JOIN [SRV1].[CDN_KNF_ONE].cdn.Katalogi ON DoN_Katalog = Ktl_KtlId