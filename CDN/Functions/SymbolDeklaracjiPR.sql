CREATE FUNCTION CDN.SymbolDeklaracjiPR(@BZdID INT)
RETURNS NVARCHAR(MAX)
AS
BEGIN
 DECLARE @retVal NVARCHAR(MAX)
 SET @retVal = ''
 DECLARE @DkNID INT
 DECLARE @podTyp INT
 DECLARE @podID INT
 SELECT @DkNID = BZd_DokumentID, @podTyp = BZd_PodmiotTyp, @podID = BZd_PodmiotID FROM cdn.BnkZdarzenia WHERE BZd_BZdID = @BZdID
 IF IsNull(@DkNID, 0) = 0
 BEGIN
  --Płatność ręczna
  IF @podTyp = 5 AND (SELECT Urz_Standardowy FROM cdn.Urzedy WHERE Urz_UrzID = @podID) = 1
   RETURN 'DRA' --podmiot to ZUS
  ELSE
   RETURN '' -- podmiot to nie ZUS
 END
 --Płatność związana z deklaracją
 DECLARE @TYP_DEKLARACJI_VAT7_OR_JPK INT,
   @NUMER_OKRESU_VAT7_OR_JPK INT,
   @TYP_DEKLARACJI_PIT36_MK INT,
   @NUMER_OKRESU_PIT36_MK INT,
   @TYP_DEKLARACJI_PIT36_R INT,
   @TYP_DEKLARACJI_PIT36L_MK INT,
   @NUMER_OKRESU_PIT36L_MK INT,
   @TYP_DEKLARACJI_PIT36L_R INT,
   @TYP_DEKLARACJI_PIT28_MK INT,
   @NUMER_OKRESU_PIT28_MK INT,
   @TYP_DEKLARACJI_PIT28_R INT,
   @TYP_DEKLARACJI_CIT8_MK INT,
   @NUMER_OKRESU_CIT8_MK INT,
   @TYP_DEKLARACJI_CIT8_R INT,
   @TYP_DEKLARACJI_PIT36_U INT,
   @TYP_DEKLARACJI_PIT36L_U INT,
   @TYP_DEKLARACJI_CIT8_U INT,
   @TYP_DEKLARACJI_ZUS_DRA INT
 SET @TYP_DEKLARACJI_VAT7_OR_JPK = 1; SET @NUMER_OKRESU_VAT7_OR_JPK = 10005
 SET @TYP_DEKLARACJI_PIT36_MK = 2; SET @NUMER_OKRESU_PIT36_MK = 250003
 SET @TYP_DEKLARACJI_PIT36_R = 15
 SET @TYP_DEKLARACJI_PIT36L_MK = 12; SET @NUMER_OKRESU_PIT36L_MK = 250003
 SET @TYP_DEKLARACJI_PIT36L_R = 16
 SET @TYP_DEKLARACJI_PIT28_MK = 4; SET @NUMER_OKRESU_PIT28_MK = 48011
 SET @TYP_DEKLARACJI_PIT28_R = 20
 SET @TYP_DEKLARACJI_CIT8_MK = 8; SET @NUMER_OKRESU_CIT8_MK = 250003
 SET @TYP_DEKLARACJI_CIT8_R = 17
 SET @TYP_DEKLARACJI_PIT36_U = 41
 SET @TYP_DEKLARACJI_PIT36L_U = 42
 SET @TYP_DEKLARACJI_CIT8_U = 40
 SET @TYP_DEKLARACJI_ZUS_DRA = 120
 DECLARE @typDeklaracji INT, @Wersja INT
 SELECT @typDeklaracji = DkN_TypDeklar, @Wersja = DkN_Wersja FROM cdn.DeklNag WHERE DkN_DkNID = @DkNID
 IF @typDeklaracji = @TYP_DEKLARACJI_VAT7_OR_JPK AND @Wersja < 21
  SELECT @retVal = CASE WHEN DkE_WartoscL = 1 THEN 'VAT7' WHEN DkE_WartoscL = 2 THEN 'VAT7K' END FROM cdn.DeklElem WHERE DkE_DkNID = @DkNID AND DkE_Numer = @NUMER_OKRESU_VAT7_OR_JPK
 IF @typDeklaracji = @TYP_DEKLARACJI_VAT7_OR_JPK AND @Wersja >= 21
  SELECT @retVal = CASE WHEN DkE_WartoscL = 1 THEN 'JPK_V7M' WHEN DkE_WartoscL = 2 THEN 'JPK_V7K' END FROM cdn.DeklElem WHERE DkE_DkNID = @DkNID AND DkE_Numer = @NUMER_OKRESU_VAT7_OR_JPK
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT36_MK
  SELECT @retVal = CASE WHEN DkE_WartoscL = 0 THEN 'PIT36_M' ELSE 'PIT36_K' END FROM cdn.DeklElem WHERE DkE_DkNID = @DkNID AND DkE_Numer = @NUMER_OKRESU_PIT36_MK
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT36_R
  SELECT @retVal = 'PIT36_R'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT36L_MK
  SELECT @retVal = CASE WHEN DkE_WartoscL = 0 THEN 'PIT36L_M' ELSE 'PIT36L_K' END FROM cdn.DeklElem WHERE DkE_DkNID = @DkNID AND DkE_Numer = @NUMER_OKRESU_PIT36L_MK
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT36L_R
  SELECT @retVal = 'PIT36L_R'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT28_MK
  SELECT @retVal = CASE WHEN DkE_WartoscTekst  = '0' THEN 'PIT28_M' ELSE 'PIT28_K' END FROM cdn.DeklElem WHERE DkE_DkNID = @DkNID AND DkE_Numer = @NUMER_OKRESU_PIT28_MK
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT28_R
  SELECT @retVal = 'PIT28_R'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_CIT8_MK
  SELECT @retVal = CASE WHEN DkE_WartoscL = 0 THEN 'CIT8_M' ELSE 'CIT8_K' END FROM cdn.DeklElem WHERE DkE_DkNID = @DkNID AND DkE_Numer = @NUMER_OKRESU_CIT8_MK
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_CIT8_R
  SELECT @retVal = 'CIT8_R'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT36_U
  SELECT @retVal = 'PIT36_U'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_PIT36L_U
  SELECT @retVal = 'PIT36L_U'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_CIT8_U
  SELECT @retVal = 'CIT8_U'
 ELSE IF @typDeklaracji = @TYP_DEKLARACJI_ZUS_DRA
  SELECT @retVal = 'DRA'
 RETURN @retVal
END
