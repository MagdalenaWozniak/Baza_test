CREATE FUNCTION CDN.CzyMoznaUstawicSEPA(@BRaID INT) RETURNS INT
AS
BEGIN
  DECLARE @BRaTyp INT
  DECLARE @CDC INT
  SELECT @BRaTyp = BRa_Typ, @CDC = IsNull(BFN_CDC, 0)
 FROM cdn.BnkRachunki
 LEFT OUTER JOIN cdn.BnkNazwy ON BNa_BNaID = BRa_BNaID
 LEFT OUTER JOIN cdn.BnkFormatyNag ON BFN_BFNID = BNa_Format
 WHERE BRa_BRaID = @BRaID
  IF @BRaTyp = 2 AND @CDC <> 0
 RETURN 1
  RETURN 0
END
