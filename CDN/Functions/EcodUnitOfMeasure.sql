CREATE FUNCTION CDN.EcodUnitOfMeasure( @JM AS nvarchar(20), @TrEId INT, @packItemUnit INT, @eFa INT)
RETURNS nvarchar(20)
AS
BEGIN
 IF @eFa = 1 RETURN @JM
 DECLARE @uJM nvarchar(20)
 SET @uJM = UPPER(@JM)
 IF @packItemUnit = 1 AND CDN.PackInUse(@TrEId) = 1
 BEGIN
  RETURN 'PA'
 END
    IF RTRIM(LTRIM(@uJM)) = 'MTR'  RETURN @uJM
    IF RTRIM(LTRIM(@uJM)) = 'MTK'  RETURN @uJM
    IF RTRIM(LTRIM(@uJM)) = 'KGM'  RETURN @uJM
    IF RTRIM(LTRIM(@uJM)) = 'LTR'  RETURN @uJM
    IF RTRIM(LTRIM(@uJM)) = 'PCE'  RETURN @uJM
    IF RTRIM(LTRIM(@uJM)) = 'PR'   RETURN @uJM
    IF RTRIM(LTRIM(@uJM)) = 'TNE'  RETURN @uJM
 IF RTRIM(LTRIM(@uJM)) = 'SZT' OR RTRIM(LTRIM(@uJM)) = 'SZT.'  RETURN 'PCE'
 IF RTRIM(LTRIM(@uJM)) = 'M'  OR RTRIM(LTRIM(@uJM)) = 'MT'    RETURN 'MTR'
 IF RTRIM(LTRIM(@uJM)) = 'M2'    OR RTRIM(LTRIM(@uJM)) = 'MKW' RETURN 'MTK'
 IF RTRIM(LTRIM(@uJM)) = 'KG' OR RTRIM(LTRIM(@uJM)) = 'KG.' OR RTRIM(LTRIM(@uJM)) = 'KILO' RETURN 'KGM'
 IF RTRIM(LTRIM(@uJM)) = 'L'  OR RTRIM(LTRIM(@uJM)) = 'L.' OR RTRIM(LTRIM(@uJM)) = 'LITR' RETURN 'LTR'
    IF RTRIM(LTRIM(@uJM)) = 'T'  OR RTRIM(LTRIM(@uJM)) = 'T.' OR RTRIM(LTRIM(@uJM)) = 'TONA' RETURN 'TNE'
 RETURN 'PCE'
END
