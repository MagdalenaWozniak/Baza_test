CREATE FUNCTION CDN.ZestKsiNumer (@ZKPId INT)
RETURNS NVARCHAR(50)
AS
BEGIN
 DECLARE @Wynik NVARCHAR(50)
 DECLARE @Lp SMALLINT
 SET @Wynik   = ''
 WHILE @ZKPId IS NOT NULL
  BEGIN
   IF NOT EXISTS (SELECT * FROM CDN.ZestKsiPoz WHERE ZKP_ZKPId = @ZKPId) BREAK
   SELECT @ZKPId = ZKP_ParId, @Lp = ZKP_Lp FROM CDN.ZestKsiPoz WHERE ZKP_ZKPId = @ZKPId
   SET @Wynik = STR(@Lp, 2) + CASE @Wynik WHEN '' THEN @Wynik ELSE '.' + @Wynik END
  END
  RETURN @Wynik
END
