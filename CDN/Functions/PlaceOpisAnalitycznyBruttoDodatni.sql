CREATE FUNCTION CDN.PlaceOpisAnalitycznyBruttoDodatni(@OPPID INT)
RETURNS DECIMAL(15, 2)
AS
BEGIN
 DECLARE @Wartosc DECIMAL(15,2)
 SELECT @Wartosc = CASE WHEN OPP_Brutto > 0 THEN OPP_Brutto ELSE 0 END
 FROM CDN.OpisPlace INNER JOIN CDN.WypElementy ON OPP_WpeId=WPE_WpeId
 INNER JOIN CDN.TypWyplata ON WPE_TWPID = TWP_TWPID
 WHERE OPP_OPPID = @OPPID and TWP_Standardowy not in (15,16,17,18,19,20)
 RETURN ISNULL(@Wartosc, 0)
END
