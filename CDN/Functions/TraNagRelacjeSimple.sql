CREATE FUNCTION [CDN].[TraNagRelacjeSimple] (@TrNId INT,@Flaga INT)
RETURNS INT
AS
BEGIN
 DECLARE @TrR_TrRID INT
 SELECT @TrR_TrRID = TrR_TrRID FROM CDN.TraNagRelacje
 WHERE TrR_TrNId = @TrNId AND TrR_FaTyp = (
 SELECT MIN(TrR_FaTyp)
 FROM CDN.TraNagRelacje WHERE TrR_TrNId = @TrNId
 GROUP BY TrR_TrNId)
 RETURN @TrR_TrRID
END
