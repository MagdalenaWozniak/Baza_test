CREATE FUNCTION CDN.AnalizyWartoscZakupu()
RETURNS @WartZakupu TABLE (
 EId  INTEGER,
 WartoscZakupu  NUMERIC(15,2)
  )
AS
--RT tu nie zmienilem realcji na polecenie SO bo nie wykorzystujemy
BEGIN
  INSERT INTO @WartZakupu(EId, WartoscZakupu)
(SELECT S1.EId,WartoscZakupu=MAX(ISNULL(S1.W,0)+ISNULL(S2.W,0)+ISNULL(S3.W,0)+ISNULL(S4.W,0))
FROM (SELECT EId=TrE_TrEId,W=ISNULL(TrE_KosztUslugi,0)FROM cdn.TraElem) AS S3
LEFT OUTER JOIN
(SELECT EId=TrE_TrEId,W=ISNULL(SUM(CASE WHEN TrS_Rodzaj in (312000,312008) AND TrS_Ilosc<0 AND TrS_ZwrId IS NULL THEN 0 ELSE TrS_Wartosc END),0)
FROM cdn.TraElem LEFT OUTER JOIN cdn.TraSElem ON TrE_TrEid=TrS_TrEId GROUP BY TrE_TrEId) AS S1 ON S3.EId=S1.EId
LEFT OUTER JOIN
(SELECT EId=FA_E.TrE_TrEId,W=ISNULL(SUM(CASE WHEN WZ_S.TrS_Rodzaj in (312000,312008) AND WZ_S.TrS_Ilosc<0 AND WZ_S.TrS_ZwrId IS NULL THEN 0 ELSE WZ_S.TrS_Wartosc END),0)
FROM cdn.TraSElem WZ_S
JOIN cdn.TraElem WZ_E ON WZ_S.TrS_TrEId=WZ_E.TrE_TrEId
JOIN cdn.TraNag WZ_N ON WZ_E.TrE_TrNId=WZ_N.TrN_TrNId
JOIN cdn.TraElem FA_E ON FA_E.TrE_TrNId=WZ_N.TrN_FaId
WHERE WZ_E.TrE_LpPow=FA_E.TrE_LpPow AND WZ_E.TrE_TypDokumentu<>318 GROUP BY FA_E.TrE_TrEId) AS S2 ON S3.EId=S2.EId
LEFT OUTER JOIN
(SELECT EId=PA_E.TrE_TrEId,W=ISNULL(SUM(CASE WHEN WZ_S.TrS_Rodzaj in (312000,312008) AND WZ_S.TrS_Ilosc<0 AND WZ_S.TrS_ZwrId IS NULL THEN 0 ELSE WZ_S.TrS_Wartosc END),0)
FROM cdn.TraSElem WZ_S
JOIN cdn.TraElem WZ_E ON WZ_S.TrS_TrEId=WZ_E.TrE_TrEId
JOIN cdn.TraNag WZ_N ON WZ_E.TrE_TrNId=WZ_N.TrN_TrNId
JOIN cdn.TraNag FA_N ON FA_N.TrN_TrNId=WZ_N.TrN_FaId
JOIN cdn.TraElem FA_E ON FA_E.TrE_TrNId=WZ_N.TrN_FaId
JOIN cdn.TraNag PA_N ON PA_N.TrN_TrNId=FA_N.TrN_FaId AND PA_N.TrN_TypDokumentu=305
JOIN cdn.TraElem PA_E ON PA_E.TrE_TrNId=PA_N.TrN_TrNId
WHERE WZ_E.TrE_LpPow=FA_E.TrE_LpPow AND PA_E.TrE_LpPow=FA_E.TrE_LpPow AND WZ_E.TrE_TypDokumentu<>318 GROUP BY PA_E.TrE_TrEId) AS S4 ON S4.EId=S3.EId
GROUP BY S1.EId)
  RETURN
END
