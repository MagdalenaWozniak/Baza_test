CREATE TABLE [CDN].[ZestKsiKol] (
    [ZKK_ZKKId]  INT           IDENTITY (1, 1) NOT NULL,
    [ZKK_ZKNId]  INT           NOT NULL,
    [ZKK_Lp]     SMALLINT      NOT NULL,
    [ZKK_Nazwa]  NVARCHAR (20) NOT NULL,
    [ZKK_Okres]  TINYINT       NOT NULL,
    [ZKK_DataOd] DATETIME      NULL,
    [ZKK_DataDo] DATETIME      NULL,
    CONSTRAINT [ZKK_Primary] PRIMARY KEY CLUSTERED ([ZKK_ZKKId] ASC) WITH (FILLFACTOR = 100),
    CONSTRAINT [FK_ZKKZestawienie] FOREIGN KEY ([ZKK_ZKNId]) REFERENCES [CDN].[ZestKsiNag] ([ZKN_ZKNId]) ON DELETE CASCADE
);


GO
CREATE NONCLUSTERED INDEX [ZKKZestawienie]
    ON [CDN].[ZestKsiKol]([ZKK_ZKNId] ASC, [ZKK_Lp] ASC) WITH (FILLFACTOR = 100);


GO
CREATE TRIGGER CDN.ZestKsiKol_Delete_Trigger
  ON CDN.ZestKsiKol
  FOR DELETE
AS
SET NOCOUNT ON
-- Kasowanie wyników
DELETE FROM CDN.ZestKsiWyniki WHERE ZKW_ZKKId IN (SELECT ZKK_ZKKId FROM deleted)
SET NOCOUNT OFF
