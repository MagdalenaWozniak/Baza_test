CREATE TABLE [CDN].[FrsPromocje] (
    [FPR_Id]    INT IDENTITY (1, 1) NOT NULL,
    [FPR_PrmId] INT NULL,
    [FPR_FrsId] INT NULL,
    CONSTRAINT [FPR_Primary] PRIMARY KEY CLUSTERED ([FPR_Id] ASC) WITH (FILLFACTOR = 80, PAD_INDEX = ON),
    CONSTRAINT [FK_FprPrm] FOREIGN KEY ([FPR_PrmId]) REFERENCES [CDN].[PrmKarty] ([PRM_Id]) ON DELETE CASCADE
);


GO
CREATE NONCLUSTERED INDEX [FprPrm]
    ON [CDN].[FrsPromocje]([FPR_PrmId] ASC) WITH (FILLFACTOR = 80, PAD_INDEX = ON);


GO
CREATE UNIQUE NONCLUSTERED INDEX [FprFrS]
    ON [CDN].[FrsPromocje]([FPR_FrsId] ASC, [FPR_PrmId] ASC) WITH (FILLFACTOR = 80, PAD_INDEX = ON);

