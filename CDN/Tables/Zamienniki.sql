CREATE TABLE [CDN].[Zamienniki] (
    [ZAM_ZamId]    INT IDENTITY (1, 1) NOT NULL,
    [ZAM_TwrId]    INT NOT NULL,
    [ZAM_ZamTwrId] INT NOT NULL,
    [ZAM_Lp]       INT NULL,
    CONSTRAINT [ZAM_Primary] PRIMARY KEY CLUSTERED ([ZAM_ZamId] ASC) WITH (FILLFACTOR = 100),
    CONSTRAINT [FK_ZamTwrId] FOREIGN KEY ([ZAM_TwrId]) REFERENCES [CDN].[Towary] ([Twr_TwrId]) ON DELETE CASCADE
);


GO
CREATE UNIQUE NONCLUSTERED INDEX [ZamTwrId]
    ON [CDN].[Zamienniki]([ZAM_TwrId] ASC, [ZAM_ZamTwrId] ASC) WITH (FILLFACTOR = 100);

