    ON [CDN].[GrupyKontElem]([GKE_AccId] ASC) WITH (FILLFACTOR = 100);


GO
CREATE UNIQUE NONCLUSTERED INDEX [GKENaglowek]
    ON [CDN].[GrupyKontElem]([GKE_GKNID] ASC, [GKE_GKEID] ASC) WITH (FILLFACTOR = 100);

