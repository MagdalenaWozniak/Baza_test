CREATE TABLE [CDN].[GrupyKontElem] (
    [GKE_GKEID] INT IDENTITY (1, 1) NOT NULL,
    [GKE_GKNID] INT NOT NULL,
    [GKE_AccId] INT NOT NULL,
    CONSTRAINT [GKE_Primary] PRIMARY KEY CLUSTERED ([GKE_GKEID] ASC) WITH (FILLFACTOR = 100),
