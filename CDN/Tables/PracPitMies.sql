CREATE TABLE [CDN].[PracPitMies] (
    [PPM_PPMId]       INT      IDENTITY (1, 1) NOT NULL,
    [PPM_PraId]       INT      NOT NULL,
    [PPM_Rok]         SMALLINT NOT NULL,
    [PPM_Miesiac]     SMALLINT NOT NULL,
    [PPM_Zablokowane] TINYINT  NOT NULL,
    CONSTRAINT [PPM_Primary] PRIMARY KEY CLUSTERED ([PPM_PPMId] ASC) WITH (FILLFACTOR = 100),
    CONSTRAINT [FK_PPMPraId] FOREIGN KEY ([PPM_PraId]) REFERENCES [CDN].[PracKod] ([PRA_PraId]) ON DELETE CASCADE
);


GO
CREATE UNIQUE NONCLUSTERED INDEX [PPMPraId]
    ON [CDN].[PracPitMies]([PPM_PraId] ASC, [PPM_Rok] ASC, [PPM_Miesiac] ASC) WITH (FILLFACTOR = 100);

