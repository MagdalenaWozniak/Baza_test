CREATE TRIGGER CDN.CfgKurierzy_Insert_Trigger
  ON CDN.CfgKurierzy
  FOR INSERT
AS
SET NOCOUNT ON
    IF EXISTS (SELECT * FROM inserted WHERE inserted.CKK_Prefix='')
        -- Sprawdzenie obecności wierszy w tabeli nadrzędnej
        begin
   update cdn.CfgKurierzy set CKK_Prefix = LEFT(CAST(NEWID() AS VARCHAR(36)), 14) where ckk_ckkid in (select ckk_ckkid from  inserted WHERE inserted.CKK_Prefix='')
        END
SET NOCOUNT OFF
