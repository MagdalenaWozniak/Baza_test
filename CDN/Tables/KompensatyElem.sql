CREATE TABLE [CDN].[KompensatyElem] (
    [KPE_KPEID] INT IDENTITY (1, 1) NOT NULL,
    [KPE_KPNID] INT NOT NULL,
    [KPE_BRKID] INT NOT NULL,
    CONSTRAINT [KPE_Primary] PRIMARY KEY CLUSTERED ([KPE_KPEID] ASC) WITH (FILLFACTOR = 100),
    CONSTRAINT [FK_KPENaglowek] FOREIGN KEY ([KPE_KPNID]) REFERENCES [CDN].[KompensatyNag] ([KPN_KPNID]) ON DELETE CASCADE,
    CONSTRAINT [FK_KPERozliczenie] FOREIGN KEY ([KPE_BRKID]) REFERENCES [CDN].[BnkRozKwoty] ([BRK_BRKID])
);


GO
CREATE UNIQUE NONCLUSTERED INDEX [KPENaglowek]
    ON [CDN].[KompensatyElem]([KPE_KPNID] ASC, [KPE_KPEID] ASC) WITH (FILLFACTOR = 100);


GO
CREATE UNIQUE NONCLUSTERED INDEX [KPERozliczenie]
    ON [CDN].[KompensatyElem]([KPE_BRKID] ASC) WITH (FILLFACTOR = 100);

