CREATE PROCEDURE [CDN].[DetalStan_DodajFakture]
@StanDetalId int,
@typDok int,
@nrNumer int,
@nrString NVARCHAR(31),
@bufor smallint,
@anulowany int,
@dataDok datetime,
@fiskalna tinyint,
@razemBrutto decimal(15,2),
@rabat decimal(5,2),
@ts_zal datetime,
@opeId int,
@FAID int,
@Waluta NVARCHAR(3),
@kontrahentId int,
@error int,
@osOdbierajaca NVARCHAR(40),
@ZmianaId int
AS
BEGIN
SET NOCOUNT ON
IF @kontrahentId is null
BEGIN
 INSERT INTO CDN.DetalStanTraNag (DSTrN_StanDetalID,
         DSTrN_TypDokumentu,
         DSTrN_NumerNr,
         DSTrN_NumerString,
         DSTrN_Bufor,
         DSTrN_Anulowany,
         DSTrN_DataDok,
         DSTrN_Fiskalna,
         DSTrN_RazemBrutto,
         DSTrN_Rabat,
         DSTrN_TS_Zal,
         DSTrN_OpeID,
         DSTrN_FAID,
         DSTrN_Waluta,
         DSTrN_FiskalnaErr,
         DSTrN_OsobaOdbierajaca,
         DSTrN_ZmianaId)
 VALUES (@StanDetalId,
   @typDok,
   @nrNumer,
   @nrString,
   @bufor,
   @anulowany,
   @dataDok,
   @fiskalna,
   @razemBrutto,
   @rabat,
   @ts_zal,
   @opeId,
   @FAID,
   @Waluta,
   @error,
   @osOdbierajaca,
   @ZmianaId)
END
ELSE
BEGIN
 INSERT INTO CDN.DetalStanTraNag (DSTrN_StanDetalID,
         DSTrN_TypDokumentu,
         DSTrN_NumerNr,
         DSTrN_NumerString,
         DSTrN_Bufor,
         DSTrN_Anulowany,
         DSTrN_DataDok,
         DSTrN_Fiskalna,
         DSTrN_RazemBrutto,
         DSTrN_Rabat,
         DSTrN_TS_Zal,
         DSTrN_OpeID,
         DSTrN_FAID,
         DSTrN_Waluta,
         DSTrN_PodID,
         DSTrN_OdbID,
         DSTrN_FiskalnaErr,
         DSTrN_OsobaOdbierajaca,
         DSTrN_ZmianaId)
 VALUES (@StanDetalId,
   @typDok,
   @nrNumer,
   @nrString,
   @bufor,
   @anulowany,
   @dataDok,
   @fiskalna,
   @razemBrutto,
   @rabat,
   @ts_zal,
   @opeId,
   @FAID,
   @Waluta,
   @kontrahentId,
   @kontrahentId,
   @error,
   @osOdbierajaca,
   @ZmianaId)
END
SET NOCOUNT OFF
END
