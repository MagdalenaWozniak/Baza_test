CREATE PROCEDURE [CDN].[DetalStan_UaktualnijKontrahenta]
@Kod NVARCHAR(20),
@EAN NVARCHAR(16),
@Nazwa1 NVARCHAR(50),
@Nazwa2 NVARCHAR(50),
@Nazwa3 NVARCHAR(250),
@Kraj NVARCHAR(40),
@Wojewodztwo NVARCHAR(40),
@Powiat NVARCHAR(40),
@Gmina NVARCHAR(40),
@Ulica NVARCHAR(40),
@NrDomu NVARCHAR(10),
@NrLokalu NVARCHAR(10),
@Miasto NVARCHAR(40),
@KodPocztowy NVARCHAR(10),
@Poczta NVARCHAR(40),
@Adres2 NVARCHAR(40),
@NipKraj NVARCHAR(2),
@NipE NVARCHAR(20),
@Nip NVARCHAR(20),
@Regon NVARCHAR(20),
@Pesel NVARCHAR(11),
@TS_Mod datetime,
@Telefon NVARCHAR(20),
@Opis NVARCHAR(254),
@Odbiorca NVARCHAR(40),
@OpeId int,
@id int
AS
BEGIN
SET NOCOUNT ON
UPDATE CDN.DetalStanKontrahenci SET
 DSKnt_Kod = @Kod,
 DSKnt_EAN = @EAN,
 DSKnt_Nazwa1 = @Nazwa1,
 DSKnt_Nazwa2 = @Nazwa2,
 DSKnt_Nazwa3 = @Nazwa3,
 DSKnt_Kraj = @Kraj,
 DSKnt_Wojewodztwo = @Wojewodztwo,
 DSKnt_Powiat = @Powiat,
 DSKnt_Gmina = @Gmina,
 DSKnt_Ulica = @Ulica,
 DSKnt_NrDomu = @NrDomu,
 DSKnt_NrLokalu = @NrLokalu,
 DSKnt_Miasto = @Miasto,
 DSKnt_KodPocztowy = @KodPocztowy,
 DSKnt_Poczta = @Poczta,
 DSKnt_Adres2 = @Adres2,
 DSKnt_NipKraj = @NipKraj,
 DSKnt_NipE = @NipE,
 DSKnt_Nip = @Nip,
 DSKnt_Regon = @Regon,
 DSKnt_Pesel = @Pesel,
 DSKnt_Telefon = @Telefon,
 DSKnt_Opis = @Opis,
 DSKnt_OsobaOdbierajaca = @Odbiorca,
 DSKnt_TS_Mod = @TS_Mod,
 DSKnt_OpeID = @OpeId
WHERE DSKnt_DSKntId = @id
SET NOCOUNT OFF
END
