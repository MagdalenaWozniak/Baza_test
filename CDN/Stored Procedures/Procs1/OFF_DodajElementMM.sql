CREATE PROCEDURE CDN.OFF_DodajElementMM
  @Tre_TwrNazwa             nvarchar(255),
  @Tre_TwrSWW               nvarchar(20),
  @Tre_WartoscBruttoChr     nvarchar(19),
  @Tre_WartoscNettoChr      nvarchar(19),
  --@Twr_GidTypChr            nvarchar(5),
  @Twr_GidNumerChr          nvarchar(11),
  @Tre_IloscChr             nvarchar(21),
  @Tre_RabatChr             nvarchar(11),
  @Tre_KursLChr             nvarchar(19),
  @Tre_KursMChr             nvarchar(11),
  @Tre_Waluta               nvarchar(5),
  @Tre_JM                   nvarchar(20),
  @Tre_StawkaChr            nvarchar(11),
  @Tre_LpChr                nvarchar(11),
  @Tre_Cena0Chr             nvarchar(19),
  @Tre_CenaWChr             nvarchar(19),
  @Tre_CenaTChr             nvarchar(19),
  @Tre_FlagaChr             nvarchar(5),
  @Tre_TwrOpis              nvarchar(1024),
  @TrN_GIDTypChr            nvarchar(5),
  @TrN_GIDNumerChr          nvarchar(11)
AS
  SET NOCOUNT ON
  DECLARE
  @Tre_WartoscBrutto       DECIMAL(15,2),
  @Tre_WartoscNetto        DECIMAL(15,2),
  @Twr_GidFirma            INT,
  @Twr_GidTyp              SMALLINT,
  @Twr_GidNumer            INT,
  @Twr_GidLp               SMALLINT,
  @Tre_Ilosc               DECIMAL(15,4),
  @Tre_Rabat               DECIMAL(5,2),
  @Tre_KursL               DECIMAL(15,4),
  @Tre_KursM               DECIMAL(5,0),
  @Tre_Stawka              DECIMAL(5,2),
  @Tre_Lp                  INT,
  @Tre_Cena0               DECIMAL(15,2),
  @Tre_CenaW               DECIMAL(15,2),
  @Tre_CenaT               DECIMAL(15,2),
  @Tre_Flaga               SMALLINT,
  @TrN_DataWys             DATETIME,
  @TrN_DataDok             DATETIME,
  @TrN_DataOpe             DATETIME,
  @TrN_GIDFirma            INT,
  @TrN_GIDTyp              SMALLINT,
  @TrN_GIDNumer            INT,
  @TrN_GIDLp               SMALLINT,
  @TrN_TypNB               TINYINT,
  @TwrId                   INT,
  @TwrNazwa                nvarchar(255),
  @TwrEAN                  nvarchar(40),
  @TwrNumerKat             nvarchar(40),
  @TwrKod                  nvarchar(50),
  @TrN_MagId               INT,
  @TrNId                   INT
  SELECT
      @Tre_WartoscBrutto       = CONVERT(DECIMAL(15,2),@Tre_WartoscBruttoChr),
      @Tre_WartoscNetto        = CONVERT(DECIMAL(15,2),@Tre_WartoscNettoChr),
      @Twr_GidFirma            = 0,
      @Twr_GidTyp              = 0,
      @Twr_GidNumer            = CONVERT(INT,@Twr_GidNumerChr),
      @Twr_GidLp               = 0,
      @Tre_Ilosc               = CONVERT(DECIMAL(15,4),@Tre_IloscChr),
      @Tre_Rabat               = CONVERT(DECIMAL(5,2),@Tre_RabatChr),
      @Tre_KursL               = CONVERT(DECIMAL(15,4),@Tre_KursLChr),
      @Tre_KursM               = CONVERT(DECIMAL(5,0), @Tre_KursMChr),
      @Tre_Stawka              = CONVERT(DECIMAL(5,2),@Tre_StawkaChr),
      @Tre_Lp                  = CONVERT(INT,@Tre_LpChr),
      @Tre_Cena0               = CONVERT(DECIMAL(15,2),@Tre_Cena0Chr),
      @Tre_CenaW               = CONVERT(DECIMAL(15,2),@Tre_CenaWChr),
      @Tre_CenaT               = CONVERT(DECIMAL(15,2),@Tre_CenaTChr),
      @Tre_Flaga               = CONVERT(SMALLINT,@Tre_FlagaChr),
      @TrN_GIDFirma            = 0,
      @TrN_GIDTyp              = CONVERT(SMALLINT,@TrN_GIDTypChr),
      @TrN_GIDNumer            = CONVERT(INT, @TrN_GIDNumerChr),
      @TrN_GIDLp               = 0
      SELECT top 1 @TrN_MagId=TrN_MagZrdId, @TrNId=Trn_TrnId,  @TrN_DataWys=TrN_DataWys,@TrN_DataDok=TrN_DataDok,@TrN_DataOpe=TrN_DataOpe,
                    @TrN_TypNB = TrN_TypNB From Cdn.TraNag Where Trn_GidNumer =@Trn_GidNumer and Trn_GidTyp= @Trn_GidTyp
      SELECT top 1 @TwrId=Twr_TwrId,@TwrNazwa=Twr_Nazwa,@TwrEAN=Twr_EAN,@TwrNumerKat=Twr_NumerKat,@TwrKod=Twr_Kod From cdn.Towary Where Twr_GidNumer = @Twr_GidNumer
      insert into Cdn.TraElem(TrE_TrNId,TrE_Lp,
            TrE_LpPow,TrE_TypDokumentu,TrE_Aktywny,TrE_DataDok,TrE_DataOpe,TrE_TwrId,
            TrE_TwrNazwa,TrE_TwrEAN,TrE_TwrNumerKat,TrE_TwrKod,TrE_TwrOpis,TrE_TwrSWW,
            TrE_Stawka,TrE_Flaga,TrE_Zrodlowa,TrE_TwCNumer,TrE_TypNB,TrE_Cena0,TrE_Rabat,
            TrE_CenaW,TrE_Waluta,TrE_KursNumer,TrE_KursL,TrE_KursM,TrE_CenaT,TrE_Ilosc,
            TrE_Jm,TrE_JmZ,TrE_JmCalkowite,TrE_JMPrzelicznikL,TrE_JMPrzelicznikM,TrE_IloscJM,
            TrE_WartoscNetto,TrE_WartoscBrutto,TrE_KosztUslugi,TrE_Cena0WD,TrE_CenaWWD,
            TrE_WartoscNettoWal,TrE_WartoscBruttoWal,TrE_Prog,TrE_UpustTyp,TrE_Upust,TrE_UpustKnt,TrE_UpustKntTyp,
            TrE_Kaucja,TrE_IloscJMKW,TrE_IloscKW, TrE_Atr1_DeAId, TrE_Atr1_Kod, TrE_Atr1_Wartosc, TrE_Atr2_DeAId,
            TrE_Atr2_Kod, TrE_Atr2_Wartosc, TrE_Atr3_DeAId, TrE_Atr3_Kod, TrE_Atr3_Wartosc, TrE_Atr4_DeAId,
            TrE_Atr4_Kod, TrE_Atr4_Wartosc, TrE_Atr5_DeAId, TrE_Atr5_Kod, TrE_Atr5_Wartosc,TrE_MagId,TrE_WartoscZakupuWylicz,
            TrE_WyborDostaw,TrE_TwrTyp,TrE_TwrKodDostawcy)
      values(@TrNId,@Tre_Lp,@Tre_Lp,312,1,@TrN_DataDok,@TrN_DataOpe,@TwrId,@Tre_TwrNazwa,@TwrEAN,@TwrNumerKat,
            @TwrKod,@Tre_TwrOpis,@Tre_TwrSWW,@Tre_Stawka,@Tre_Flaga,0,1,@TrN_TypNB,@Tre_Cena0,@Tre_Rabat,@Tre_CenaW,@Tre_Waluta,
            0,1,1,@Tre_CenaT,@Tre_Ilosc,@Tre_JM,'',0,1,1,@Tre_Ilosc,@Tre_WartoscNetto,@Tre_WartoscBrutto,0,@Tre_Cena0,@Tre_CenaW,
            @Tre_WartoscNetto,@Tre_WartoscBrutto,0,0,0,0,0,0,0,0,NULL,'','',NULL,'','',NULL,'','',NULL,'','',NULL,'','',@TrN_MagId,0,
            0,1,'')
  SET NOCOUNT OFF
