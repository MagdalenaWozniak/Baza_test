CREATE PROCEDURE CDN.GetKlasaOpis
@Klasa int
AS
BEGIN
 SELECT
 case @Klasa
 when 101  then   'Ewidencja dodatkowa przychodów'
 when 102  then   'Ewidencja dodatkowa kosztów'
 when 111  then   'Potwierdzenie salda KH'
 when 112  then   'Ponaglenie zapłaty KH'
 when 113  then   'Nota odsetkowa KH'
 when 114  then   'Delegacja'
 when 115  then   'PK kompensaty'
 when 116  then   'Różnica kursowa KH'
 when 500  then   'Bilans otwarcia'
 when 201  then   'Wypłata'
 when 202  then   'Wpłata'
 when 211  then   'Raport kasa/bank'
 when 211  then   'Nota odsetkowa'
 when 222  then   'Ponaglenie zapłaty'
 when 223  then   'Potwierdzenie salda'
  when 224  then     'Różnica kursowa'
  when 225  then     'Różnica kursowa MW'
 when 226  then     'Kompensata'
 when 301  then   'Faktura zakupu'
 when 302  then   'Faktura sprzedaży'
 when 303  then   'Przyjęcie wewnętrzne'
 when 304  then   'Rozchód wewnętrzny'
 when 305   then  'Paragon'
 when 306  then   'Wydanie zewnętrzne'
 when 307  then   'Przyjęcie zewnętrzne'
 when 308  then   'Rezerwacja odbiorcy'
 when 309  then   'Zamówienie u dostawcy'
 when 310  then   'Bilans otwarcia magazynu'
 when 311  then   'Arkusz inwentaryzacyjny'
 when 312  then   'Przesunięcie międzymagazynowe'
 when 313  then   'Faktura zaliczkowa'
 when 314  then   'Wydanie kaucji'
 when 317  then   'Przyjęcie wewnętrzne produktów'
 when 318  then   'Rozchód wewnętrzny składników'
    when 320  then       'Faktura proforma'
    when 321  then       'Faktura wewnętrzna zakupu'
    when 322  then       'Faktura wewnętrzna sprzedaży'
    when 350  then      'Faktura dla rolnika ryczałtowego'
    when 370  then      'Zlecenie nadania paczki'
 when 400  then   'Umowa'
 when 600  then   'Lista płac'
    when 700  then    'Kontakt'
    when 800  then     'Oferta MS Word'
 when 650 then    'Etat korygująca'
 when 221 then   'Nota odsetkowa'
 when 900 then    'Zlecenie serwisowe'
 when 345 then   'Dokument TaxFree'
 when 750 then   'Obieg dokumentów'
 when 1010 then   'Wiadomość przychodząca'
 when 1011   then   'Wiadomość wychodząca'
 when 1012   then   'Identyfikator księgowy'
 when 1020   then   'Wiadomość SMS'
  when 1111   then   'Arkusz inwent. ST'
  when 1112   then   'Arkusz inwent. WYP'
-- when 900302 then   'Faktury sprzedaży - zlecenie serwisowe'
-- when 900304 then   'Rozchody wewnętrzne - zlecenie serwisowe'
-- when 900305 then   'Paragony - zlecenie serwisowe'
-- when 900306 then   'Wydania zewnętrzne - zlecenie serwisowe'
-- when 900309 then   'Zamówienia ZD - zlecenie serwisowe'
-- when 900312 then   'Przesunięcia MM - zlecenie serwisowe'
 else ''
 end as Opis
END
